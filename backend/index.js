app.put("/UpdateAccounting/:id", async (req, res) => {
  const id = parseInt(req.params.id, 10);
  if (isNaN(id)) return res.status(400).json({ message: "Invalid accounting ID" });

  const {
    username,
    plan_date,
    amount,
    package: pkg,
    price_on_me,
    remaining_payment,
    remaining_package,
    is_paid,
    remaining_changed
  } = req.body;

  try {
    // 1️⃣ Fetch current record
    const { rows } = await safeQuery(
      `SELECT username, plan_date, amount, package, price_on_me, remaining_payment, remaining_package, remaining_changed, is_paid
       FROM accounting_invoices
       WHERE id = $1`,
      [id]
    );
    if (rows.length === 0) return res.status(404).json({ message: "Record not found" });

    const oldRecord = rows[0];

    // 2️⃣ Normalize date
    const normalizedPlanDate = plan_date ? new Date(plan_date).toISOString().split("T")[0] : null;

    // 3️⃣ Update record
    await safeQuery(
      `UPDATE accounting_invoices
       SET username = COALESCE($1, username),
           plan_date = COALESCE($2, plan_date),
           amount = COALESCE($3, amount),
           package = COALESCE($4, package),
           price_on_me = COALESCE($5, price_on_me),
           remaining_payment = $6,
           remaining_package = $7,
           remaining_changed = $8,
           is_paid = $9,
           updated_at = CURRENT_TIMESTAMP
       WHERE id = $10`,
      [username, normalizedPlanDate, amount, pkg, price_on_me, remaining_payment, remaining_package, remaining_changed, is_paid, id]
    );

    // 4️⃣ Insert field logs
    const fields = [
      { name: "username", oldValue: oldRecord.username, newValue: username },
      { name: "plan_date", oldValue: oldRecord.plan_date, newValue: normalizedPlanDate },
      { name: "amount", oldValue: oldRecord.amount, newValue: amount },
      { name: "package", oldValue: oldRecord.package, newValue: pkg },
      { name: "price_on_me", oldValue: oldRecord.price_on_me, newValue: price_on_me },
      { name: "remaining_payment", oldValue: oldRecord.remaining_payment, newValue: remaining_payment },
      { name: "remaining_package", oldValue: oldRecord.remaining_package, newValue: remaining_package }
    ];

    for (const field of fields) {
      if ((field.oldValue ?? "").toString() !== (field.newValue ?? "").toString()) {
        const comment = `${field.name} changed from "${field.oldValue ?? ''}" to "${field.newValue ?? ''}"`;
        await safeQuery(
          `INSERT INTO accounting_logs (accounting_id, field_name, old_value, new_value, comment)
           VALUES ($1, $2, $3, $4, $5)`,
          [id, field.name, field.oldValue, field.newValue, comment]
        );
      }
    }

    // 5️⃣ Log remaining_package changes separately
    if ((oldRecord.remaining_package ?? "").toString() !== (remaining_package ?? "").toString()) {
      await safeQuery(
        `INSERT INTO remaining_package_logs (accounting_id, previous_value, updated_value)
         VALUES ($1, $2, $3)`,
        [id, oldRecord.remaining_package, remaining_package]
      );
    }

    res.status(200).json({ message: "Record updated successfully", remaining_changed });
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: "Internal Server Error" });
  }
});



